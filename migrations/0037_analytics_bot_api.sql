-- phase: expand
-- The bot API counters of openvibe-shared 4.113.0 (2026-11-06): AnalyticsTrackerPg's option
-- countBotApiAtIngest writes a bot's API call into analytics_bot_api_hourly/daily instead of a raw
-- analytics_events row, and aggregate() adds those hits to the hour's/day's rollup. The option is off
-- here, but aggregate() reads both tables, so they exist from now on.
--
-- The DDL is openvibe-shared/analytics/pg.js analyticsSchema(), like migrations/0002_analytics.sql.
CREATE TABLE IF NOT EXISTS analytics_bot_api_hourly (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service text NOT NULL, hour text NOT NULL,
    endpoint_group text NOT NULL, status_class text NOT NULL, bot_family text NOT NULL,
    hits bigint NOT NULL DEFAULT 0,
    UNIQUE (service, hour, endpoint_group, status_class, bot_family)
);
CREATE TABLE IF NOT EXISTS analytics_bot_api_daily (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service text NOT NULL, date text NOT NULL,
    endpoint_group text NOT NULL, status_class text NOT NULL, bot_family text NOT NULL,
    hits bigint NOT NULL DEFAULT 0,
    UNIQUE (service, date, endpoint_group, status_class, bot_family)
);
