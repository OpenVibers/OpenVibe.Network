CREATE FUNCTION users_profile_changed() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN IF COALESCE(NEW.is_anon, 0) = 0 AND (OLD.username IS DISTINCT FROM NEW.username OR OLD.display_name IS DISTINCT FROM NEW.display_name OR OLD.avatar_url IS DISTINCT FROM NEW.avatar_url OR OLD.profile_color IS DISTINCT FROM NEW.profile_color OR OLD.role IS DISTINCT FROM NEW.role OR OLD.is_banned IS DISTINCT FROM NEW.is_banned) THEN INSERT INTO user_profile_changes (user_id, changed, at) VALUES (NEW.id, trim((CASE WHEN OLD.username IS DISTINCT FROM NEW.username THEN 'username ' ELSE '' END) || (CASE WHEN OLD.display_name IS DISTINCT FROM NEW.display_name THEN 'display_name ' ELSE '' END) || (CASE WHEN OLD.avatar_url IS DISTINCT FROM NEW.avatar_url THEN 'avatar_url ' ELSE '' END) || (CASE WHEN OLD.profile_color IS DISTINCT FROM NEW.profile_color THEN 'profile_color ' ELSE '' END) || (CASE WHEN OLD.role IS DISTINCT FROM NEW.role THEN 'role ' ELSE '' END) || (CASE WHEN OLD.is_banned IS DISTINCT FROM NEW.is_banned THEN 'banned ' ELSE '' END)), (extract(epoch FROM statement_timestamp()) * 1000)::bigint); END IF; RETURN NULL; END $$;
CREATE TRIGGER users_profile_changed AFTER UPDATE OF username, display_name, avatar_url, profile_color, role, is_banned ON users FOR EACH ROW EXECUTE FUNCTION users_profile_changed();

CREATE FUNCTION users_profile_created() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN IF COALESCE(NEW.is_anon, 0) = 0 THEN INSERT INTO user_profile_changes (user_id, changed, at) VALUES (NEW.id, 'created', (extract(epoch FROM statement_timestamp()) * 1000)::bigint); END IF; RETURN NULL; END $$;
CREATE TRIGGER users_profile_created AFTER INSERT ON users FOR EACH ROW EXECUTE FUNCTION users_profile_created();

