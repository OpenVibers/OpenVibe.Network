CREATE FUNCTION user_modules_guard_users_delete() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN IF OLD.subject_id IS NOT NULL AND EXISTS (SELECT 1 FROM user_modules WHERE subject_id = OLD.subject_id) THEN RAISE EXCEPTION 'user_modules rows remain for this subject: call modules.onSubjectRemoved or onSubjectMerged first'; END IF; RETURN OLD; END $$;
CREATE TRIGGER user_modules_guard_users_delete BEFORE DELETE ON users FOR EACH ROW EXECUTE FUNCTION user_modules_guard_users_delete();

CREATE FUNCTION user_modules_guard_users_rekey() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN IF OLD.subject_id IS NOT NULL AND NEW.subject_id IS DISTINCT FROM OLD.subject_id AND EXISTS (SELECT 1 FROM user_modules WHERE subject_id = OLD.subject_id) THEN RAISE EXCEPTION 'user_modules rows remain for this subject: call modules.onSubjectMerged first'; END IF; RETURN NEW; END $$;
CREATE TRIGGER user_modules_guard_users_rekey BEFORE UPDATE OF subject_id ON users FOR EACH ROW EXECUTE FUNCTION user_modules_guard_users_rekey();

