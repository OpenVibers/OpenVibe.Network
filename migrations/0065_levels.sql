-- Network owns earned experience; no amount is spendable or convertible.
CREATE TABLE IF NOT EXISTS person_levels (
    user_id bigint PRIMARY KEY REFERENCES users(id),
    xp bigint NOT NULL DEFAULT 0 CHECK (xp BETWEEN 0 AND 1000000000000),
    level integer NOT NULL DEFAULT 1 CHECK (level >= 1),
    leaderboard boolean NOT NULL DEFAULT true
);
CREATE TABLE IF NOT EXISTS experience_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id),
    service text NOT NULL,
    reason text NOT NULL,
    amount bigint NOT NULL CHECK (amount > 0),
    idempotency_key text NOT NULL,
    earned_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(service, idempotency_key)
);
CREATE INDEX IF NOT EXISTS experience_person_recent ON experience_events(user_id, earned_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS experience_week ON experience_events(earned_at, user_id);
CREATE INDEX IF NOT EXISTS person_levels_board ON person_levels(xp DESC, user_id) WHERE leaderboard;
CREATE TABLE IF NOT EXISTS experience_service_days (
    service text NOT NULL,
    day date NOT NULL,
    amount bigint NOT NULL,
    PRIMARY KEY(service, day)
);
