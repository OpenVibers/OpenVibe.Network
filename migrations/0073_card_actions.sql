-- phase: expand
-- Ask 287: the user card's actions. Mutes, friendships and user reports, beside blocks.
-- Mutes hush one person's non-staff notices the way blocks stop them; friendships are
-- mutual adds (friends when both directions are active); reports queue for staff.
-- Nothing here changes an existing table, and no production setting is touched.
CREATE TABLE IF NOT EXISTS user_mutes (
    muter_subject text COLLATE "C" NOT NULL,
    muted_subject text COLLATE "C" NOT NULL,
    active bigint NOT NULL DEFAULT 1 CHECK (active IN (0, 1)),
    revision bigint NOT NULL DEFAULT 1 CHECK (revision >= 1),
    created_at text COLLATE "C" NOT NULL DEFAULT ov_now_iso(),
    updated_at text COLLATE "C" NOT NULL DEFAULT ov_now_iso(),
    PRIMARY KEY (muter_subject, muted_subject),
    CHECK (muter_subject <> muted_subject)
);
CREATE INDEX IF NOT EXISTS idx_user_mutes_muted ON user_mutes(muted_subject, active);

CREATE TABLE IF NOT EXISTS user_friends (
    user_subject text COLLATE "C" NOT NULL,
    friend_subject text COLLATE "C" NOT NULL,
    active bigint NOT NULL DEFAULT 1 CHECK (active IN (0, 1)),
    revision bigint NOT NULL DEFAULT 1 CHECK (revision >= 1),
    created_at text COLLATE "C" NOT NULL DEFAULT ov_now_iso(),
    updated_at text COLLATE "C" NOT NULL DEFAULT ov_now_iso(),
    PRIMARY KEY (user_subject, friend_subject),
    CHECK (user_subject <> friend_subject)
);
CREATE INDEX IF NOT EXISTS idx_user_friends_friend ON user_friends(friend_subject, active);

CREATE TABLE IF NOT EXISTS user_reports (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_subject text COLLATE "C" NOT NULL,
    target_subject text COLLATE "C" NOT NULL,
    reason text COLLATE "C" NOT NULL,
    detail text COLLATE "C" NOT NULL DEFAULT '',
    status text COLLATE "C" NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'reviewed', 'dismissed')),
    created_at text COLLATE "C" NOT NULL DEFAULT ov_now_iso(),
    updated_at text COLLATE "C" NOT NULL DEFAULT ov_now_iso(),
    CHECK (reporter_subject <> target_subject)
);
CREATE INDEX IF NOT EXISTS idx_user_reports_target ON user_reports(target_subject, status);
CREATE INDEX IF NOT EXISTS idx_user_reports_reporter ON user_reports(reporter_subject, target_subject);
-- One open report per pair: filing again while it is open returns the open one, never a duplicate.
CREATE UNIQUE INDEX IF NOT EXISTS uq_user_reports_open ON user_reports(reporter_subject, target_subject) WHERE status = 'open';
