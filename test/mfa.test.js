'use strict';
const assert = require('assert');
const crypto = require('crypto');
const express = require('express');
const bcrypt = require('bcryptjs');
const cookieParser = require('cookie-parser');
const { getDb } = require('../server/db/database');
const auth = require('../server/auth/routes');
const mfa = require('../server/auth/mfa');
const { verifySession } = require('../server/auth/session');
const accountData = require('../server/identity/account-data');
(async () => {
    process.env.NETWORK_MFA_KEY = crypto.randomBytes(32).toString('hex');
    const realNow = Date.now; let now = realNow(); Date.now = () => now;
    const db = getDb();
    const pw = 'test-only-password';
    await db.prepare('INSERT INTO users (id, username, password_hash) VALUES (?, ?, ?), (?, ?, ?)').run(71, 'mfa_alice', bcrypt.hashSync(pw, 4), 72, 'mfa_bob', bcrypt.hashSync(pw, 4));
    const keys = crypto.generateKeyPairSync('rsa', { modulusLength: 2048, publicKeyEncoding: { type: 'spki', format: 'pem' }, privateKeyEncoding: { type: 'pkcs8', format: 'pem' } });
    const config = { jwt: { issuer: 'https://openvibe.network', accessTokenExpiry: '1h' } };
    const app = express(); app.use(express.json()); app.use(cookieParser());
    Object.assign(app.locals, { db, config, ...keys }); app.use('/api/auth', auth);
    const server = app.listen(0, '127.0.0.1'); await new Promise(r => server.on('listening', r));
    const base = `http://127.0.0.1:${server.address().port}/api/auth`;
    const alice = await db.prepare('SELECT * FROM users WHERE id = 71').get();
    const bob = await db.prepare('SELECT * FROM users WHERE id = 72').get();
    const at = auth.signToken(alice, keys.privateKey, config); const bt = auth.signToken(bob, keys.privateKey, config);
    const call = async (path, body, token, cookies) => {
        const res = await fetch(base + path, { method: body === undefined ? 'GET' : 'POST', headers: { 'content-type': 'application/json', ...(token ? { authorization: `Bearer ${token}` } : {}), ...(cookies ? { cookie: cookies } : {}) }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) });
        return { status: res.status, body: await res.json(), cookies: res.headers.getSetCookie(), cache: res.headers.get('cache-control') };
    };
    const cookieOf = (r, name) => r.cookies.find(s => s.startsWith(name + '='))?.split(';')[0];
    const login = () => call('/login', { username: alice.username, password: pw });
    const code = secret => mfa.totp(secret).generate({ timestamp: now });
    try {
        let r = await login(); assert.equal(r.status, 200); assert.ok(r.body.token, 'flag-off login unchanged');
        r = await call('/mfa/enroll', { password: pw }, at); assert.equal(r.status, 404);
        await db.prepare("UPDATE site_settings SET value = 'all' WHERE key = 'mfa_enrollment'").run();
        r = await call('/mfa/enroll', { password: 'wrong' }, at); assert.equal(r.status, 401);
        r = await call('/mfa/enroll', { password: pw }, at); assert.equal(r.status, 200); assert.equal(r.cache, 'no-store');
        const secret = r.body.secret; assert.match(r.body.qr, /^data:image\/png;base64,/);
        let f = await db.prepare('SELECT * FROM user_mfa WHERE user_id = 71').get();
        assert.ok(!f.secret_ciphertext); assert.ok(!f.pending_secret_ciphertext.includes(secret));
        assert.equal((await login()).status, 200, 'unconfirmed enrollment does not affect login');
        assert.equal((await call('/mfa/confirm', { code: code(secret), user_id: 71 }, bt)).status, 401, 'other person cannot confirm');
        assert.equal((await call('/mfa/confirm', { code: 'wrong' }, at)).status, 401);
        await db.prepare('UPDATE user_mfa SET pending_until = ? WHERE user_id = 71').run(now - 1);
        assert.equal((await call('/mfa/confirm', { code: code(secret) }, at)).status, 401, 'expired enrollment');
        await db.prepare('UPDATE user_mfa SET pending_until = ? WHERE user_id = 71').run(now + 600000);
        r = await call('/mfa/confirm', { code: code(secret) }, at); assert.equal(r.status, 200); const recovery = r.body.recovery_codes;
        assert.equal(recovery.length, 10); assert.equal(new Set(recovery).size, 10);
        assert.equal((await call('/mfa/confirm', { code: code(secret) }, at)).status, 401, 'cannot confirm twice');
        assert.ok(!(await verifySession(at, { db, publicKey: keys.publicKey, config })).error, 'existing session untouched');
        r = await login(); assert.equal(r.status, 202); assert.ok(!r.body.token); let pending = cookieOf(r, '__Host-ov_mfa_pending');
        assert.ok(pending); assert.ok(r.cookies.every(c => !c.startsWith('ov_token=')));
        assert.match(r.cookies[0], /HttpOnly/); assert.match(r.cookies[0], /Secure/);
        assert.ok((await verifySession(pending.split('=')[1], { db, publicKey: keys.publicKey, config })).error);
        assert.equal((await call('/mfa/verify', { code: code(secret) }, null, pending)).status, 401, 'enrollment step cannot be replayed');
        now += 61000;
        r = await call('/mfa/verify', { code: code(secret), remember: true }, null, pending); assert.equal(r.status, 200);
        const remembered = cookieOf(r, '__Host-ov_mfa_device'); assert.ok(remembered);
        assert.equal((await call('/mfa/verify', { code: recovery[0] }, null, pending)).status, 401, 'consumed pending state');
        r = await call('/login', { username: alice.username, password: pw }, null, remembered); assert.equal(r.status, 200, 'remembered browser');
        r = await call('/login', { username: alice.username, password: pw }, null, remembered + 'bad'); assert.equal(r.status, 202, 'bad device signature');
        r = await call('/mfa', undefined, at); assert.equal(r.body.devices.length, 1); const deviceId = r.body.devices[0].id;
        await call('/mfa/devices/revoke', { id: deviceId }, bt);
        assert.equal((await call('/login', { username: alice.username, password: pw }, null, remembered)).status, 200, 'other person cannot revoke device');
        await call('/mfa/devices/revoke', { id: deviceId }, at);
        assert.equal((await call('/login', { username: alice.username, password: pw }, null, remembered)).status, 202, 'revocation enforced');
        now += 61000;
        r = await login(); pending = cookieOf(r, '__Host-ov_mfa_pending');
        const concurrent = await Promise.all([call('/mfa/verify', { code: recovery[0] }, null, pending), call('/mfa/verify', { code: recovery[0] }, null, pending)]);
        assert.deepEqual(concurrent.map(x => x.status).sort(), [200, 401], 'recovery and state are atomic');
        pending = cookieOf(await login(), '__Host-ov_mfa_pending');
        assert.equal((await call('/mfa/verify', { code: recovery[0] }, null, pending)).status, 401, 'used recovery code refused');
        await db.prepare('UPDATE mfa_challenges SET expires_at = ? WHERE user_id = 71').run(now - 1);
        assert.equal((await call('/mfa/verify', { code: recovery[1] }, null, pending)).status, 401, 'expired pending state');
        // Five failures per account, even across newly issued pending states.
        await db.prepare('UPDATE user_mfa SET failures = 0, locked_until = 0 WHERE user_id = 71').run();
        for (let i = 0; i < 5; i++) {
            pending = cookieOf(await login(), '__Host-ov_mfa_pending');
            assert.equal((await call('/mfa/verify', { code: 'wrong' }, null, pending)).status, 401);
        }
        assert.equal((await login()).status, 429);
        assert.equal((await call('/mfa/verify', { code: recovery[1] }, null, pending)).status, 401, 'correct code also waits');
        now += 301000;
        pending = cookieOf(await login(), '__Host-ov_mfa_pending');
        assert.equal((await call('/mfa/verify', { code: recovery[1] }, null, pending)).status, 200, 'works after wait');
        const part = await accountData.networkPart(db, alice.id);
        const exported = JSON.stringify(part);
        assert.ok(!exported.includes(secret)); assert.ok(!exported.includes(recovery[2]));
        for (const name of ['user_mfa', 'mfa_challenges', 'mfa_recovery_codes', 'mfa_devices']) assert.ok(part.files.some(f => f.name === name + '.json'));
        await db.prepare("UPDATE site_settings SET value = 'off' WHERE key = 'mfa_enrollment'").run();
        assert.equal((await login()).status, 202, 'enrollment switch never bypasses existing MFA');
        const key = process.env.NETWORK_MFA_KEY; delete process.env.NETWORK_MFA_KEY;
        assert.equal((await login()).status, 503, 'missing key fails closed'); process.env.NETWORK_MFA_KEY = key;
        assert.equal((await call('/mfa/disable', { code: recovery[2], user_id: 71 }, bt)).status, 401, 'other account');
        assert.equal((await call('/mfa/disable', { code: recovery[0] }, at)).status, 401, 'used code cannot disable');
        assert.equal((await call('/mfa/disable', { code: recovery[2] }, at)).status, 200);
        assert.equal((await login()).status, 200);
        for (const table of ['user_mfa', 'mfa_challenges', 'mfa_recovery_codes', 'mfa_devices']) assert.equal((await db.prepare(`SELECT COUNT(*) AS n FROM ${table} WHERE user_id = 71`).get()).n, 0);
        console.log('MFA: enrollment, expiry, replay, five-attempt lockout, recovery race, remembered browser, account isolation, export, flag-off and fail-closed checks passed');
    } finally { Date.now = realNow; server.close(); await globalThis.__ovNetworkTestDbClose?.(); }
})().catch(err => { console.error('MFA tests failed (assertion details redacted)'); console.error(String(err.stack).split('\n').filter(line => /^\s+at /.test(line)).slice(0, 4).join('\n')); process.exitCode = 1; });
