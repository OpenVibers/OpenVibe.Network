'use strict';
const assert = require('assert');
const express = require('express');
const { getDb } = require('../server/db/database');
const { createPublicProfiles } = require('../server/profile/public');
const { createUserCards, TTL_MS } = require('../server/profile/card');
const cors = require('../server/public-cors');
(async () => {
    const db = getDb();
    const subject = 'usr_01JZ0000000000000000000AAA';
    await db.prepare("INSERT INTO users(username,password_hash,display_name,subject_id) VALUES ('CardTest','x','Card Test',?)").run(subject);
    const user = await db.prepare("SELECT id FROM users WHERE username='CardTest'").get();
    let clock = Date.now(), calls = 0, down = false;
    const fetchImpl = async (url, options) => {
        calls++;
        assert.strictEqual(options.redirect, 'error');
        if (down) throw new Error('down');
        if (url.endsWith('/streak')) {
            assert.strictEqual(options.headers.Authorization, 'Bearer test-service');
            return { ok: true, json: async () => ({ streak: 3 }) };
        }
        return { ok: true, json: async () => ({ channel: { username: 'CardTest' }, streams: [{ id: 1 }] }) };
    };
    const profiles = createPublicProfiles({ db });
    profiles.badgesOf = async () => down ? { unavailable: true } : { badges: [{ id: 'one' }] };
    const cards = createUserCards({ db, profiles, selfToken: () => 'test-service', fetchImpl, now: () => clock });
    const app = express(); app.use(express.json());
    app.get('/api/v1/people/:username/card', cors.publicCors, cards.api);
    app.use('/settings', cards.settings((req, res, next) => { req.user = user; next(); }));
    const server = await new Promise(resolve => { const s = app.listen(0, '127.0.0.1', () => resolve(s)); });
    const base = `http://127.0.0.1:${server.address().port}`;
    const get = () => fetch(base + '/api/v1/people/CardTest/card');
    try {
        assert.strictEqual((await get()).status, 503, 'owner switch defaults off');
        await db.prepare("UPDATE site_settings SET value='true' WHERE key='user_card_enabled'").run();
        const responses = await Promise.all([get(), get(), get()]);
        const card = await responses[0].json();
        assert.strictEqual(responses[0].headers.get('cache-control'), 'no-store');
        assert.strictEqual(responses[0].headers.get('access-control-allow-origin'), '*');
        assert.ok(cors.isPublicDiscoveryPath('/api/v1/people/CardTest/card'));
        assert.deepStrictEqual(card, { username: 'CardTest', display_name: 'Card Test', profile_url: 'https://openvibe.network/@CardTest', avatar_url: 'https://openvibe.network/avatar/CardTest?s=160', level: 1, followers: 0, badges_count: 1, streak: 3, channel_url: 'https://openvibe.live/@CardTest', live: { now: true, site: 'live', url: 'https://openvibe.live/@CardTest' } });
        assert.strictEqual(calls, 2, 'concurrent reads coalesce');
        await get(); assert.strictEqual(calls, 2, 'warm read reuses aggregate');
        clock += TTL_MS + 1; await get(); assert.strictEqual(calls, 4, 'expires after 30 seconds');
        await db.prepare("INSERT INTO user_history(user_id,service,type,title,url) VALUES (?, 'live', 'stream', 'private title', 'https://openvibe.live/@Someone')").run(user.id);
        const put = body => fetch(base + '/settings', { method: 'PUT', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
        assert.strictEqual((await put({ active_sites: true })).status, 200);
        let visible = await (await get()).json();
        assert.ok(visible.active_sites.some(s => s.id === 'live'));
        assert.ok(!JSON.stringify(visible).includes('private title'));
        assert.strictEqual((await put({ active_sites: null })).status, 400);
        await put({ level: false, streak: false, followers: false, badges_count: false, avatar_url: false, active_sites: false });
        visible = await (await get()).json();
        for (const field of ['level', 'streak', 'followers', 'badges_count', 'avatar_url', 'active_sites']) assert.ok(!(field in visible), field + ' absent immediately');
        await db.prepare("UPDATE users SET public_page_places = '{\"live\":false}' WHERE id=?").run(user.id);
        visible = await (await get()).json();
        assert.ok(!('live' in visible) && !('channel_url' in visible));
        await db.prepare("UPDATE users SET profile_public=0, card_visibility='{}'::jsonb WHERE id=?").run(user.id);
        visible = await (await get()).json();
        assert.deepStrictEqual(Object.keys(visible).sort(), ['avatar_url', 'display_name', 'profile_url', 'username']);
        await db.prepare("UPDATE users SET profile_public=1, public_page_places='{}' WHERE id=?").run(user.id);
        await db.prepare("INSERT INTO person_presence(subject_id,state,show_status) VALUES (?, 'invisible', 1)").run(subject);
        visible = await (await get()).json();
        assert.ok(!('live' in visible), 'invisible overrides the card live setting');
        await db.prepare('DELETE FROM person_presence WHERE subject_id=?').run(subject);
        await db.prepare('INSERT INTO person_levels(user_id,leaderboard) VALUES (?, false)').run(user.id);
        visible = await (await get()).json();
        assert.ok(!('level' in visible), 'leaderboard opt-out overrides card visibility');
        await db.prepare("INSERT INTO username_history(user_id,old_username,new_username) VALUES (?, 'OldCard', 'CardTest')").run(user.id);
        const moved = await fetch(base + '/api/v1/people/OldCard/card', { redirect: 'manual' });
        assert.strictEqual(moved.status, 307);
        assert.strictEqual(moved.headers.get('location'), '/api/v1/people/CardTest/card');
        down = true; clock += TTL_MS + 1;
        visible = await (await get()).json();
        assert.ok(!('streak' in visible) && !('badges_count' in visible) && !('live' in visible), 'source failures are absent, never zero');
        await db.prepare('UPDATE users SET is_banned=1 WHERE id=?').run(user.id);
        assert.strictEqual((await get()).status, 404, 'bans bypass cache');
        console.log('user-card: off switch, public shape, 30s coalesced cache, privacy on warm reads, opt-in sites, failure omission and bans passed');
    } finally { await new Promise(resolve => server.close(resolve)); }
})().catch(e => { console.error(e); process.exitCode = 1; });
