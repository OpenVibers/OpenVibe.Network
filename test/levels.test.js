'use strict';
const assert = require('assert');
const { getDb } = require('../server/db/database');
const levels = require('../server/levels/store');
const wallet = require('../server/coins/wallet');
const { backfill } = require('../scripts/backfill-levels');
(async () => {
    const db = getDb();
    const { ids } = require('openvibe-contracts');
    const subject = ids.newId('user');
    const user = await db.prepare("INSERT INTO users(username, password_hash, subject_id) VALUES ('levels_probe', 'unused', ?) RETURNING id").get(subject);
    const award = (key, amount = 25) => levels.award(db, 'quest', { subject, reason: 'quest.completed', amount, idempotency_key: key });
    assert.equal((await levels.byUsername(db, 'levels_probe')).level, 1);
    await award('one', 100);
    await assert.rejects(award('one', 100), e => e.status === 409);
    assert.equal((await levels.byUsername(db, 'levels_probe')).xp, 100);
    assert.equal((await levels.batch(db, [subject])).levels[subject], 2);
    await assert.rejects(levels.batch(db, Array(101).fill(subject)), e => e.status === 400);
    await wallet.credit(db, { user_id: user.id, app_id: 'quest', amount: 10, reason: 'quest:first-follow', idempotency_key: 'qcp:earned' });
    await wallet.credit(db, { user_id: user.id, app_id: 'quest', amount: 10, reason: 'quest:first-follow', idempotency_key: 'qcp:earned' });
    await wallet.credit(db, { user_id: user.id, app_id: 'live', amount: 10, reason: 'Refund: example', idempotency_key: 'refund:1' });
    await wallet.credit(db, { user_id: user.id, app_id: 'live', amount: 10, reason: 'Admin grant', idempotency_key: 'admin:1' });
    assert.equal((await levels.person(db, user.id)).xp, 110, 'only earned coins, exactly once');
    const other = await db.prepare("INSERT INTO users(username, password_hash, subject_id) VALUES ('levels_other', 'unused', ?) RETURNING id").get(ids.newId('user'));
    await wallet.transfer(db, { from_user_id: user.id, to_user_id: other.id, app_id: 'quest', amount: 5, reason: 'quest:first-follow', idempotency_key: 'transfer:1' });
    assert.equal((await levels.person(db, other.id)).xp, 0, 'transfer never earns');
    const board = await levels.board(db, user.id);
    assert(board.all_time.me); assert(board.week.me);
    await db.prepare('UPDATE person_levels SET leaderboard = false WHERE user_id = ?').run(user.id);
    assert.equal((await levels.board(db, user.id)).all_time.me, null);
    assert.equal((await levels.byUsername(db, 'levels_probe')).level, 2);
    await assert.rejects(award('over-cap', 10000), e => e.status === 429);
    assert.equal((await levels.person(db, user.id)).xp, 110, 'quota refusal rolls back');
    await db.prepare('UPDATE users SET is_banned = 1 WHERE id = ?').run(other.id);
    assert.equal((await levels.batch(db, [subject])).levels[subject], 2);
    const dry = await backfill(db); assert.equal(dry.awarded, 0); assert.equal(dry.existing, 1);
    const applied = await backfill(db, { apply: true }); assert.equal(applied.awarded, 0);
    await db.prepare('UPDATE users SET is_banned = 0 WHERE id = ?').run(other.id);
    console.log('levels: duplicate refused; earned coins once; refunds/transfers excluded; privacy, caps and dry-run passed');
    process.exit(0);
})().catch(e => { console.error(e); process.exit(1); });
